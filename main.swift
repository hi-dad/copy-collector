// Copy Collector: while collecting, every ⌘C is added to a pile and the whole pile is put back
// on the clipboard, so one ⌘V pastes everything you've copied.

enum Format: String, CaseIterable {
    case plain, quote, numbered
    var label: String {
        switch self {
        case .plain: return "Plain"
        case .quote: return "Quote  (> line)"
        case .numbered: return "Numbered"
        }
    }
}

// Password managers mark secrets with these types; never collect them.
let skipTypes: Set<String> = ["org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType",
                              "org.nspasteboard.AutoGeneratedType", "com.agilebits.onepassword"]

final class Collector: ObservableObject {
    static let shared = Collector()
    private let d = UserDefaults.standard
    private let pb = NSPasteboard.general

    @Published var collecting: Bool {
        didSet {
            d.set(collecting, forKey: "collecting")
            if collecting && !oldValue { lastSeen = pb.changeCount; writePile() }
            if !collecting && oldValue { keepLastOnly() }
            onChange?(); onPanel?()
        }
    }
    @Published var items: [String] {
        didSet {
            d.set(items, forKey: "items")
            if items.count < 2 { autoPanelDismissed = false }
            onChange?(); onPanel?()
        }
    }
    @Published var panelShown: Bool { didSet { d.set(panelShown, forKey: "panelShown"); onPanel?() } }
    @Published var autoPanel: Bool { didSet { d.set(autoPanel, forKey: "autoPanel"); onPanel?() } }
    var autoPanelDismissed = false      // closed by hand; stays closed until the pile drops below 2
    /// While collecting, the floating panel shows when switched on, or (optionally) while 2+ items are waiting.
    var panelVisible: Bool {
        collecting && (panelShown || (autoPanel && !autoPanelDismissed && items.count >= 2))
    }
    @Published var clearAfterPaste: Bool { didSet { d.set(clearAfterPaste, forKey: "clearAfterPaste"); onPasteSetting?() } }
    @Published var format: Format { didSet { d.set(format.rawValue, forKey: "format"); refreshPile(pb.changeCount == pileChange) } }
    @Published var expireMinutes: Int { didSet { d.set(expireMinutes, forKey: "expireMinutes") } }
    @Published var emptyCopyClears: Bool { didSet { d.set(emptyCopyClears, forKey: "emptyCopyClears"); onPasteSetting?() } }
    @Published var keysAllowed = true   // Input Monitoring granted (needed to see ⌘V / ⌘C)
    @Published var ignoreRepeats: Bool { didSet { d.set(ignoreRepeats, forKey: "ignoreRepeats") } }
    @Published var toast: Bool { didSet { d.set(toast, forKey: "toast") } }
    @Published var pulse: Bool { didSet { d.set(pulse, forKey: "pulse") } }
    @Published var atLogin = SMAppService.mainApp.status == .enabled {
        didSet { try? atLogin ? SMAppService.mainApp.register() : SMAppService.mainApp.unregister() }
    }

    var onChange: (() -> Void)?        // redraw icon / panel title
    var onAdded: (() -> Void)?         // pulse + toast
    var onPanel: (() -> Void)?         // show / hide floating panel
    var onPasteSetting: (() -> Void)?  // start / stop the ⌘V watcher

    private var lastSeen: Int
    private var pileChange = -1        // changeCount of our last pile write
    private var lastCopyKey = Date.distantPast
    private var lastAdded = Date()   // a pile left alone for expireMinutes is forgotten: clear it

    init() {
        d.register(defaults: ["collecting": false, "panelShown": false, "autoPanel": true,
                              "clearAfterPaste": true, "emptyCopyClears": true,
                              "format": Format.plain.rawValue, "expireMinutes": 5, "ignoreRepeats": true,
                              "toast": false, "pulse": true])
        collecting = d.bool(forKey: "collecting")
        items = d.stringArray(forKey: "items") ?? []
        panelShown = d.bool(forKey: "panelShown")
        autoPanel = d.bool(forKey: "autoPanel")
        clearAfterPaste = d.bool(forKey: "clearAfterPaste")
        emptyCopyClears = d.bool(forKey: "emptyCopyClears")
        format = Format(rawValue: d.string(forKey: "format") ?? "") ?? .plain
        expireMinutes = d.integer(forKey: "expireMinutes")
        ignoreRepeats = d.bool(forKey: "ignoreRepeats")
        toast = d.bool(forKey: "toast")
        pulse = d.bool(forKey: "pulse")
        lastSeen = pb.changeCount
    }

    var combined: String {
        switch format {
        case .quote:
            return items.map { $0.split(separator: "\n", omittingEmptySubsequences: false)
                .map { "> " + $0 }.joined(separator: "\n") }.joined(separator: "\n\n")
        case .plain:
            return items.joined(separator: "\n\n")
        case .numbered:
            return items.enumerated().map { "\($0.offset + 1). \($0.element)" }.joined(separator: "\n\n")
        }
    }

    /// Called on a timer: notices a new copy and adds it to the pile.
    func poll() {
        if !items.isEmpty && Date().timeIntervalSince(lastAdded) > Double(expireMinutes * 60) { clearAll() }
        let c = pb.changeCount
        guard c != lastSeen else { return }
        lastSeen = c
        guard collecting else { return }
        if (pb.types ?? []).contains(where: { skipTypes.contains($0.rawValue) }) { return }
        guard let raw = pb.string(forType: .string) else { return }   // images, files: leave alone
        // Only a ⌘C adds to the pile, so apps that borrow the clipboard (dictation, password managers) are ignored.
        if PasteWatcher.shared.isRunning && Date().timeIntervalSince(lastCopyKey) > 1 {
            if raw == combined { pileChange = c }   // an app put our pile back after borrowing the clipboard
            return
        }
        let s = raw.trimmingCharacters(in: .whitespacesAndNewlines)
        guard !s.isEmpty else { return }
        if ignoreRepeats && items.contains(s) { writePile(); return }
        items.append(s)
        lastAdded = Date()
        writePile()
        onAdded?()
    }

    private func writePile() {
        guard collecting, !items.isEmpty else { return }
        pb.clearContents()
        pb.setString(combined, forType: .string)
        lastSeen = pb.changeCount
        pileChange = lastSeen
    }

    /// The clipboard still holds our pile, even if another app wrote the same text back.
    private var ownsClipboard: Bool {
        !items.isEmpty && (pb.changeCount == pileChange || pb.string(forType: .string) == combined)
    }

    /// Rewrites the clipboard only if it held our pile (not something copied while off).
    private func refreshPile(_ owned: Bool) {
        guard owned else { return }
        if items.isEmpty { pb.clearContents(); lastSeen = pb.changeCount; pileChange = -1 }
        else { writePile() }
    }

    func remove(_ i: Int) { let owned = ownsClipboard; items.remove(at: i); refreshPile(owned) }
    func clearAll() { let owned = ownsClipboard; items = []; refreshPile(owned) }

    /// Turning collecting off goes back to a normal clipboard: the pile empties and only the last copy stays.
    private func keepLastOnly() {
        guard let last = items.last else { return }
        let owned = ownsClipboard
        items = []
        if owned { pb.clearContents(); pb.setString(last, forType: .string); lastSeen = pb.changeCount }
        pileChange = -1
    }

    func copyOne(_ i: Int) {
        pb.clearContents()
        pb.setString(items[i], forType: .string)
        lastSeen = pb.changeCount
    }

    /// ⌘C was pressed. If nothing new lands on the clipboard (nothing was selected), clear the pile.
    func didCopyKey() {
        lastCopyKey = Date()
        guard emptyCopyClears, collecting, !items.isEmpty else { return }
        let before = pb.changeCount
        DispatchQueue.main.asyncAfter(deadline: .now() + 0.5) {
            if self.pb.changeCount == before { self.clearAll() }
        }
    }

    /// ⌘V was pressed somewhere. If it pasted the pile, empty the pile and the clipboard,
    /// so a later ⌘V can't paste old things by surprise.
    func didPaste() {
        guard clearAfterPaste, collecting, ownsClipboard else { return }
        let pasted = pb.changeCount
        DispatchQueue.main.asyncAfter(deadline: .now() + 0.4) {
            self.items = []
            if self.pb.changeCount == pasted { self.pb.clearContents(); self.lastSeen = self.pb.changeCount }
            self.pileChange = -1
        }
    }
}

// MARK: - Menu bar icon: a number in a circle

func circleIcon(_ text: String, filled: Bool) -> NSImage {
    let font = NSFont.monospacedDigitSystemFont(ofSize: 10.5, weight: .semibold)
    let attrs: [NSAttributedString.Key: Any] = [.font: font, .foregroundColor: NSColor.black]
    let ts = (text as NSString).size(withAttributes: attrs)
    let h: CGFloat = 16
    let w = max(h, ts.width + 9)   // 10+ stretches into a pill
    let img = NSImage(size: NSSize(width: w + 2, height: 18), flipped: false) { _ in
        let r = NSRect(x: 1, y: 1, width: w, height: h).insetBy(dx: 0.75, dy: 0.75)
        let path = NSBezierPath(roundedRect: r, xRadius: r.height / 2, yRadius: r.height / 2)
        let at = NSPoint(x: r.midX - ts.width / 2, y: r.midY - ts.height / 2 + 0.5)
        if filled {
            NSColor.black.setFill(); path.fill()
            NSGraphicsContext.current?.compositingOperation = .destinationOut
        } else {
            path.lineWidth = 1.5; NSColor.black.setStroke(); path.stroke()
        }
        (text as NSString).draw(at: at, withAttributes: attrs)
        return true
    }
    img.isTemplate = true
    return img
}

// MARK: - ⌘V / ⌘C watcher (for "clear after pasting" and "empty ⌘C clears"; needs Input Monitoring)

final class PasteWatcher {
    static let shared = PasteWatcher()
    private var tap: CFMachPort?
    private var retry: Timer?
    var isRunning: Bool { tap != nil }

    func update() {
        let c = Collector.shared
        if c.clearAfterPaste || c.emptyCopyClears { start() } else { stop(); c.keysAllowed = true }
    }

    private func start() {
        guard tap == nil else { return }
        if !CGPreflightListenEventAccess() { CGRequestListenEventAccess() }
        let mask = CGEventMask(1 << CGEventType.keyDown.rawValue)
        tap = CGEvent.tapCreate(tap: .cgSessionEventTap, place: .headInsertEventTap, options: .listenOnly,
                                eventsOfInterest: mask, callback: { _, type, event, _ in
            if type == .tapDisabledByTimeout || type == .tapDisabledByUserInput {
                if let t = PasteWatcher.shared.tap { CGEvent.tapEnable(tap: t, enable: true) }
            } else if event.flags.contains(.maskCommand),
                      event.getIntegerValueField(.keyboardEventAutorepeat) == 0 {
                let key = event.getIntegerValueField(.keyboardEventKeycode)
                if key == Int64(kVK_ANSI_V) { DispatchQueue.main.async { Collector.shared.didPaste() } }
                if key == Int64(kVK_ANSI_C) && !event.flags.contains(.maskControl) {   // ⌃⌥C is our hotkey
                    DispatchQueue.main.async { Collector.shared.didCopyKey() }
                }
            }
            return Unmanaged.passUnretained(event)
        }, userInfo: nil)
        if Collector.shared.keysAllowed != (tap != nil) { Collector.shared.keysAllowed = tap != nil }
        UserDefaults.standard.set(tap != nil ? "running" : "needs permission", forKey: "keyWatcherStatus")
        if tap != nil || retry == nil {
            NSLog("Copy Collector key watcher: %@", tap != nil ? "running" : "waiting for Input Monitoring permission")
        }
        if let t = tap {
            retry?.invalidate(); retry = nil
            CFRunLoopAddSource(CFRunLoopGetMain(), CFMachPortCreateRunLoopSource(nil, t, 0), .commonModes)
            CGEvent.tapEnable(tap: t, enable: true)
        } else if retry == nil {
            // Permission not granted yet; keep trying until it is.
            retry = Timer.scheduledTimer(withTimeInterval: 2, repeats: true) { _ in self.start() }
        }
    }

    private func stop() {
        retry?.invalidate(); retry = nil
        if let t = tap { CGEvent.tapEnable(tap: t, enable: false); CFMachPortInvalidate(t) }
        tap = nil
    }

    static func openSettings() {
        NSWorkspace.shared.open(URL(string: "x-apple.systempreferences:com.apple.preference.security?Privacy_ListenEvent")!)
    }
}

// MARK: - App

let menuWidth: CGFloat = 375
let menuListMax: CGFloat = 325

final class DropPanel: NSPanel {
    override var canBecomeKey: Bool { true }
}


final class AppDelegate: NSObject, NSApplicationDelegate, NSWindowDelegate {
    let c = Collector.shared
    var item: NSStatusItem!
    var drop: DropPanel?
    var dropHost: NSView?
    var lastClose = Date.distantPast
    var sizeWatch: AnyCancellable?
    var clickMonitor: Any?
    var panel: NSPanel?
    var toastPanel: NSPanel?
    var flashing = false

    func applicationDidFinishLaunching(_ n: Notification) {
        let me = NSRunningApplication.current
        if NSRunningApplication.runningApplications(withBundleIdentifier: Bundle.main.bundleIdentifier ?? "")
            .contains(where: { $0 != me }) {
            NSApp.terminate(nil); return
        }

        item = NSStatusBar.system.statusItem(withLength: NSStatusItem.variableLength)
        item.button?.target = self
        item.button?.action = #selector(togglePopover)

        c.onChange = { [weak self] in self?.refresh() }
        c.onAdded = { [weak self] in self?.added() }
        c.onPanel = { [weak self] in self?.syncPanel() }
        c.onPasteSetting = { PasteWatcher.shared.update() }
        refresh()
        syncPanel()
        PasteWatcher.shared.update()

        let t = Timer(timeInterval: 0.25, repeats: true) { _ in Collector.shared.poll() }
        RunLoop.main.add(t, forMode: .common)
        registerHotKey()
    }

    @objc func togglePopover() {
        if drop?.isVisible == true { closeDrop(); return }
        // The same click on the icon may already have closed it (focus loss / outside-click watcher)
        // a moment before this runs; in that case the click meant "close", so don't reopen.
        if Date().timeIntervalSince(lastClose) < 0.4 { return }
        openDrop()
    }

    // The dropdown is our own panel (not NSPopover) so its top edge stays pinned under the icon
    // while it grows and shrinks.
    func openDrop() {
        if drop == nil {
            let p = DropPanel(contentRect: NSRect(x: 0, y: 0, width: menuWidth, height: 200),
                              styleMask: [.borderless, .nonactivatingPanel], backing: .buffered, defer: false)
            p.isOpaque = false; p.backgroundColor = .clear; p.hasShadow = true
            p.level = .popUpMenu
            p.collectionBehavior = [.canJoinAllSpaces, .fullScreenAuxiliary]
            p.isReleasedWhenClosed = false
            let fx = NSVisualEffectView()
            fx.material = .popover; fx.state = .active; fx.blendingMode = .behindWindow
            fx.wantsLayer = true; fx.layer?.cornerRadius = 12; fx.layer?.masksToBounds = true
            let h = NSHostingView(rootView: MenuView().environmentObject(c))
            dropHost = h
            // Whenever the list or settings change, re-measure and resize (top edge stays put).
            sizeWatch = c.objectWillChange.merge(with: UIState.shared.objectWillChange)
                .sink { [weak self] _ in DispatchQueue.main.async { self?.fitDrop() } }
            h.autoresizingMask = [.width, .height]
            fx.addSubview(h)
            p.contentView = fx
            h.frame = fx.bounds
            p.delegate = self
            drop = p
        }
        fitDrop()
        drop?.makeKeyAndOrderFront(nil)
        item.button?.highlight(true)
        clickMonitor = NSEvent.addGlobalMonitorForEvents(matching: [.leftMouseDown, .rightMouseDown]) { [weak self] _ in
            self?.closeDrop()
        }
    }

    func closeDrop() {
        if drop?.isVisible == true { lastClose = Date() }
        drop?.orderOut(nil)
        item.button?.highlight(false)
        if let m = clickMonitor { NSEvent.removeMonitor(m); clickMonitor = nil }
    }

    func fitDrop() {
        guard let h = dropHost else { return }
        placeDrop(height: ceil(h.fittingSize.height))
    }

    func placeDrop(height: CGFloat) {
        guard let p = drop, let b = item.button, let bw = b.window, height > 0 else { return }
        let icon = bw.convertToScreen(b.convert(b.bounds, to: nil))
        let screen = bw.screen?.visibleFrame ?? NSScreen.main!.visibleFrame
        let x = min(max(icon.midX - menuWidth / 2, screen.minX + 8), screen.maxX - menuWidth - 8)
        p.setFrame(NSRect(x: x, y: icon.minY - 6 - height, width: menuWidth, height: height), display: true)
    }

    func windowDidResignKey(_ n: Notification) {
        guard (n.object as? NSPanel) === drop else { return }
        // A click on the icon itself also takes focus away; let the icon's own toggle close it,
        // otherwise it would close here and immediately reopen.
        if let b = item.button, let bw = b.window,
           bw.convertToScreen(b.convert(b.bounds, to: nil)).contains(NSEvent.mouseLocation) { return }
        closeDrop()
    }

    func refresh() {
        guard !flashing else { return }
        let b = item.button
        b?.image = circleIcon(c.collecting ? "\(c.items.count)" : "", filled: false)
        b?.appearsDisabled = !c.collecting
        b?.toolTip = c.collecting ? "Copy Collector: \(c.items.count) ready to paste" : "Copy Collector: off"
        panel?.title = "Collected · \(c.items.count)"
    }

    func added() {
        if c.pulse {
            flashing = true
            item.button?.image = circleIcon("\(c.items.count)", filled: true)
            DispatchQueue.main.asyncAfter(deadline: .now() + 0.22) { self.flashing = false; self.refresh() }
        }
        if c.toast { showToast() }
    }

    func syncPanel() {
        if c.panelVisible {
            if panel == nil {
                let p = NSPanel(contentRect: NSRect(x: 0, y: 0, width: 280, height: 380),
                                styleMask: [.titled, .closable, .resizable, .utilityWindow, .nonactivatingPanel],
                                backing: .buffered, defer: false)
                p.isFloatingPanel = true
                p.level = .floating
                p.hidesOnDeactivate = false
                p.becomesKeyOnlyIfNeeded = true
                p.isReleasedWhenClosed = false
                p.collectionBehavior = [.canJoinAllSpaces, .fullScreenAuxiliary]
                p.contentViewController = NSHostingController(rootView: PanelView().environmentObject(c))
                p.setContentSize(NSSize(width: 280, height: 380))
                if !p.setFrameUsingName("CollectPanel"), let s = NSScreen.main?.visibleFrame {
                    p.setFrameTopLeftPoint(NSPoint(x: s.maxX - 300, y: s.maxY - 20))
                }
                p.setFrameAutosaveName("CollectPanel")
                p.delegate = self
                panel = p
                refresh()
            }
            panel?.orderFrontRegardless()
        } else {
            panel?.orderOut(nil)
        }
    }

    func windowWillClose(_ n: Notification) {
        guard (n.object as? NSPanel) === panel else { return }
        if c.items.count >= 2 { c.autoPanelDismissed = true }   // don't pop straight back up
        c.panelShown = false
    }

    func showToast() {
        toastPanel?.orderOut(nil)
        let v = NSHostingView(rootView: ToastView(count: c.items.count))
        v.frame.size = v.fittingSize
        let p = NSPanel(contentRect: NSRect(origin: .zero, size: v.fittingSize),
                        styleMask: [.borderless, .nonactivatingPanel], backing: .buffered, defer: false)
        p.isOpaque = false; p.backgroundColor = .clear; p.hasShadow = true
        p.level = .statusBar; p.ignoresMouseEvents = true
        p.collectionBehavior = [.canJoinAllSpaces, .fullScreenAuxiliary]
        p.contentView = v
        // Centered just above the pointer, where you're looking (kept on screen).
        let m = NSEvent.mouseLocation, size = v.fittingSize
        if let s = (NSScreen.screens.first { NSMouseInRect(m, $0.frame, false) } ?? NSScreen.main)?.visibleFrame {
            p.setFrameOrigin(NSPoint(x: min(max(m.x - size.width / 2, s.minX), s.maxX - size.width),
                                     y: min(max(m.y + 4, s.minY), s.maxY - size.height)))
        }
        p.orderFrontRegardless()
        toastPanel = p
        DispatchQueue.main.asyncAfter(deadline: .now() + 1.1) {
            NSAnimationContext.runAnimationGroup({ $0.duration = 0.3; p.animator().alphaValue = 0 },
                                                 completionHandler: { p.orderOut(nil) })
        }
    }

    // Control + Option + C turns collecting on/off from anywhere.
    func registerHotKey() {
        var spec = EventTypeSpec(eventClass: OSType(kEventClassKeyboard), eventKind: UInt32(kEventHotKeyPressed))
        InstallEventHandler(GetApplicationEventTarget(), { _, _, _ in
            DispatchQueue.main.async { Collector.shared.collecting.toggle() }
            return noErr
        }, 1, &spec, nil, nil)
        var ref: EventHotKeyRef?
        RegisterEventHotKey(UInt32(kVK_ANSI_C), UInt32(controlKey | optionKey),
                            EventHotKeyID(signature: OSType(0x434C_4354), id: 1),
                            GetApplicationEventTarget(), 0, &ref)
    }
}

// MARK: - Views

// Small view state (command-line swiftc can't use the @State macro).
final class UIState: ObservableObject {
    static let shared = UIState()
    @Published var hover: String?
    @Published var copied: String?
    @Published var showSettings = false
}

struct ItemRow: View {
    @EnvironmentObject var c: Collector
    let index: Int
    let text: String
    var highlight = false
    var place = ""
    @ObservedObject var ui = UIState.shared
    var key: String { "\(place)-\(index)" }
    var hover: Bool { ui.hover == key }
    var copied: Bool { ui.copied == key }

    var body: some View {
        HStack(alignment: .top, spacing: 8) {
            Text("\(index + 1)").font(.caption.monospacedDigit()).foregroundStyle(.tertiary)
                .frame(width: 16, alignment: .trailing).padding(.top, 1)
            Text(text).font(.callout).lineLimit(3).frame(maxWidth: .infinity, alignment: .leading)
                .foregroundStyle(highlight ? Color.accentColor : .primary)
            Button { c.copyOne(index); ui.copied = key
                let k = key
                DispatchQueue.main.asyncAfter(deadline: .now() + 1) { if ui.copied == k { ui.copied = nil } }
            } label: { Image(systemName: copied ? "checkmark" : "doc.on.doc").frame(width: 16) }
                .buttonStyle(.plain).foregroundStyle(hover || copied ? .secondary : .tertiary).help("Copy just this one")
            Button { c.remove(index) } label: { Image(systemName: "xmark") }
                .buttonStyle(.plain).foregroundStyle(hover ? .secondary : .tertiary).help("Remove")
        }
        .padding(.vertical, 6).padding(.horizontal, 6)
        .contentShape(Rectangle())
        .background(RoundedRectangle(cornerRadius: 6).fill(highlight ? Color.accentColor.opacity(0.12)
                                                          : hover ? Color.primary.opacity(0.05) : .clear))
        .onHover { h in if h { ui.hover = key } else if ui.hover == key { ui.hover = nil } }
    }
}

struct ItemList: View {
    @EnvironmentObject var c: Collector
    var highlightLast = false
    var place = ""
    var maxHeight: CGFloat? = nil

    var body: some View {
        if c.items.isEmpty {
            Text(c.collecting ? "Copy something to start." : "Turn on collecting, then copy as you read.")
                .font(.callout).foregroundStyle(.secondary)
                .frame(maxWidth: .infinity, minHeight: 60)
        } else {
            ScrollViewReader { proxy in
                ScrollView {
                    VStack(spacing: 2) {
                        ForEach(Array(c.items.enumerated()), id: \.offset) { i, s in
                            ItemRow(index: i, text: s, highlight: highlightLast && i == c.items.count - 1, place: place).id(i)
                        }
                    }
                    .padding(.trailing, 14)   // leave room for the scrollbar so it never covers the X
                }
                .frame(maxHeight: maxHeight ?? .infinity)
                .fixedSize(horizontal: false, vertical: maxHeight != nil)
                .onChange(of: c.items.count) { n in
                    if n > 0 { withAnimation { proxy.scrollTo(n - 1, anchor: .bottom) } }
                }
                .onAppear { proxy.scrollTo(c.items.count - 1, anchor: .bottom) }
            }
        }
    }
}

struct MenuView: View {
    @EnvironmentObject var c: Collector
    @ObservedObject var ui = UIState.shared
    var showSettings: Bool { ui.showSettings }

    var body: some View {
        VStack(alignment: .leading, spacing: 10) {
            HStack {
                Text("Collecting").font(.headline)
                Spacer()
                Toggle("", isOn: $c.collecting).toggleStyle(.switch).labelsHidden()
            }
            Divider()
            ItemList(place: "menu", maxHeight: menuListMax)
            Divider()
            if !c.keysAllowed {
                HStack(alignment: .top, spacing: 8) {
                    Image(systemName: "exclamationmark.triangle").foregroundStyle(.orange)
                    VStack(alignment: .leading, spacing: 4) {
                        Text("Allow Input Monitoring so pasting (or ⌘C on nothing) can clear the pile. Turn on Copy Collector in the list, then reopen this menu.")
                            .font(.caption).fixedSize(horizontal: false, vertical: true)
                        Button("Open Settings") { PasteWatcher.openSettings() }.controlSize(.small)
                    }
                }
                Divider()
            }
            Toggle("Floating panel", isOn: $c.panelShown)
            HStack {
                Button("Clear all") { c.clearAll() }.disabled(c.items.isEmpty)
                Spacer()
                Button { ui.showSettings.toggle() } label: {
                    Image(systemName: showSettings ? "gearshape.fill" : "gearshape")
                }.help("Settings")
            }
            if showSettings {
                Divider()
                Toggle("Show panel when 2+ items are waiting", isOn: $c.autoPanel)
                Toggle("Clear after pasting", isOn: $c.clearAfterPaste)
                Toggle("⌘C with nothing selected clears", isOn: $c.emptyCopyClears)
                Picker("Clear when no new copy for", selection: $c.expireMinutes) {
                    Text("2 min").tag(2); Text("5 min").tag(5)
                }.pickerStyle(.segmented)
                Picker("Format", selection: $c.format) {
                    ForEach(Format.allCases, id: \.self) { Text($0.label).tag($0) }
                }
                Toggle("Ignore repeats", isOn: $c.ignoreRepeats)
                Toggle("Pulse icon on copy", isOn: $c.pulse)
                Toggle("Show “Added” bubble", isOn: $c.toast)
                Toggle("Open at login", isOn: $c.atLogin)
                Text("Only ⌘C adds to the pile. Dictation apps and other tools that borrow the clipboard are ignored.")
                    .font(.caption).foregroundStyle(.secondary).fixedSize(horizontal: false, vertical: true)
                HStack {
                    Text("⌃⌥C turns collecting on/off").font(.caption).foregroundStyle(.secondary)
                    Spacer()
                    Button("Quit") { NSApp.terminate(nil) }
                }
            }
        }
        .padding(14)
        .frame(width: menuWidth)
        .fixedSize(horizontal: false, vertical: true)
        .frame(maxHeight: .infinity, alignment: .top)
    }
}

struct PanelView: View {
    @EnvironmentObject var c: Collector

    var body: some View {
        VStack(alignment: .leading, spacing: 8) {
            ItemList(highlightLast: true, place: "panel")
            Spacer(minLength: 0)
            HStack {
                Circle().fill(c.collecting ? Color.green : Color.secondary).frame(width: 7, height: 7)
